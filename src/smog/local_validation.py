"""Local validation: our sensor-based Lahore PM2.5 against Punjab EPA's own reference stations.

Our target comes from OpenAQ sensors (mostly low-cost). Punjab EPA runs government reference
monitoring stations and shows their hourly PM2.5 on aqi.punjab.gov.pk. We copied station readings
for a few hours into config/punjab_epa_reference.csv (one row per station, with the source link),
and compare them with our city value for the same hour.

How the hours are matched: the EPA page labels a reading with a clock time (e.g. 03:00 PKT). We treat
it as the hour that ENDS at that time, so it matches our hour that STARTS one hour earlier (OpenAQ
labels hours by their start). Because the page does not say whether its value is a 1-hour or a
24-hour average, we also show our mean of the 24 hours before.

This is a spot check on a handful of hours, not a full validation. Anyone can add rows to the CSV
(open aqi.punjab.gov.pk/lahore, copy the station PM2.5 column) and re-run `python -m smog validate-local`.
"""
from __future__ import annotations

import pandas as pd

from smog import config

REFERENCE_FILE = "config/punjab_epa_reference.csv"
OUT_CSV = "reports/local_validation.csv"
OUT_MD = "reports/LOCAL_VALIDATION.md"


def load_reference() -> pd.DataFrame:
    df = pd.read_csv(config.ROOT / REFERENCE_FILE)
    df["time_pkt"] = pd.to_datetime(df["time_pkt"])
    return df


def epa_snapshots(ref: pd.DataFrame) -> pd.DataFrame:
    """One row per (time, city): the EPA stations' mean and median PM2.5."""
    g = ref.dropna(subset=["pm25_ugm3"]).groupby(["time_pkt", "city_id"])
    out = g.agg(epa_mean=("pm25_ugm3", "mean"), epa_median=("pm25_ugm3", "median"),
                epa_min=("pm25_ugm3", "min"), epa_max=("pm25_ugm3", "max"),
                epa_stations=("station", "nunique"), source_url=("source_url", "first")).reset_index()
    out["hour_start_utc"] = (out["time_pkt"] - pd.Timedelta(hours=6)).dt.tz_localize("UTC")   # -5 h PKT, -1 h end->start
    return out


def compare(snap: pd.DataFrame, hourly: pd.DataFrame) -> pd.DataFrame:
    """Join EPA snapshots with our city-hourly medians (pure pandas, so it can be tested)."""
    h = hourly.copy()
    h["ts_utc"] = pd.to_datetime(h["ts_utc"], utc=True)
    rows = []
    for s in snap.itertuples():
        city = h[h["city_id"] == s.city_id]
        same = city[city["ts_utc"] == s.hour_start_utc]
        day = city[(city["ts_utc"] > s.hour_start_utc - pd.Timedelta(hours=24)) & (city["ts_utc"] <= s.hour_start_utc)]
        ours = float(same["pm25_median"].iloc[0]) if len(same) else None
        rows.append({
            "time_pkt": s.time_pkt.strftime("%Y-%m-%d %H:%M"), "city_id": s.city_id,
            "epa_stations": s.epa_stations, "epa_mean": round(s.epa_mean, 1), "epa_range": f"{s.epa_min:g}-{s.epa_max:g}",
            "ours_same_hour": ours, "our_sensors": int(same["n_sensors"].iloc[0]) if len(same) else 0,
            "ours_24h_mean": round(float(day["pm25_median"].mean()), 1) if len(day) else None,
            "difference": round(ours - s.epa_mean, 1) if ours is not None else None,
            "ratio": round(ours / s.epa_mean, 2) if ours is not None and s.epa_mean else None,
            "inside_epa_station_range": (s.epa_min <= ours <= s.epa_max) if ours is not None else None,
            "source_url": s.source_url})
    return pd.DataFrame(rows)


def summarise(df: pd.DataFrame) -> dict:
    ok = df.dropna(subset=["difference"])
    if ok.empty:
        return {"hours_compared": 0}
    return {"hours_compared": len(ok),
            "mean_difference": round(float(ok["difference"].mean()), 1),        # ours minus EPA (µg/m³)
            "mean_abs_difference": round(float(ok["difference"].abs().mean()), 1),
            "mean_ratio": round(float(ok["ratio"].mean()), 2),
            "inside_station_range": int(ok["inside_epa_station_range"].sum())}


def write_markdown(df: pd.DataFrame, s: dict) -> str:
    lines = ["# Local validation against Punjab EPA reference stations", "",
             "Spot check: our Lahore city value (median of OpenAQ sensors) against the mean of Punjab EPA's",
             "government monitoring stations for the same hour (aqi.punjab.gov.pk). Generated by",
             "`python -m smog validate-local` from `config/punjab_epa_reference.csv`.", ""]
    if not s.get("hours_compared"):
        lines.append("No hours could be compared yet (our data does not cover the reference hours).")
    else:
        direction = "higher" if s["mean_difference"] > 0 else "lower"
        lines += [f"**{s['hours_compared']} hours compared.** On average our value was {abs(s['mean_difference'])} µg/m³ "
                  f"{direction} than the EPA station mean (average ratio {s['mean_ratio']}); it fell inside the range of the "
                  f"EPA stations in {s['inside_station_range']} of {s['hours_compared']} hours.", ""]
    cols = ["time_pkt", "epa_stations", "epa_mean", "epa_range", "ours_same_hour", "our_sensors", "ours_24h_mean", "difference", "ratio"]
    lines.append("| " + " | ".join(cols) + " |")
    lines.append("|" + "---|" * len(cols))
    for r in df.to_dict("records"):
        lines.append("| " + " | ".join("" if r[c] is None or (isinstance(r[c], float) and pd.isna(r[c])) else str(r[c]) for c in cols) + " |")
    lines += ["", "Limits: only a few hours; the EPA readings were copied from news reports of the EPA dashboard (links in",
              "the CSV); the page does not state its averaging period, so the 24-hour column is shown too; EPA stations",
              "and our sensors are at different places in the city. A systematic difference here would be a reason to",
              "correct the low-cost sensors before using them for official decisions."]
    return "\n".join(lines) + "\n"


def run() -> str:
    from smog import warehouse
    snap = epa_snapshots(load_reference())
    with warehouse.connect(read_only=True) as con:
        hourly = con.execute("SELECT city_id, ts_utc, pm25_median, n_sensors FROM gold.city_hourly WHERE ts_utc >= ?",
                             [snap["hour_start_utc"].min() - pd.Timedelta(hours=25)]).df()
    df = compare(snap, hourly)
    s = summarise(df)
    (config.ROOT / "reports").mkdir(exist_ok=True)
    df.to_csv(config.ROOT / OUT_CSV, index=False)
    (config.ROOT / OUT_MD).write_text(write_markdown(df, s), encoding="utf-8")
    return f"{s} -> {OUT_CSV}, {OUT_MD}"
