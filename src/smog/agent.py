"""Insight Agent: answers questions about the smog forecast with citations, or says "I don't know".

How it works (plain words)
--------------------------
1. SOURCES. Two kinds, each with an id that the answer must cite:
   - documents: short, faithful summaries of official sources in knowledge/*.md (WHO, US EPA,
     Pakistan NEQS, Punjab government), plus this project's own model card. Split into small
     chunks, e.g. [doc:who-aqg-2021#1].
   - data facts: sentences built by code (not by the language model) from the published gold rows:
     tomorrow's forecasts, the last 7 measured days, data freshness, run status and test results,
     e.g. [row:pred|lahore|20261021|20261020T1511].
2. RETRIEVE. TF-IDF search (scikit-learn) picks the 4 document chunks closest to the question.
   Urdu questions are first translated to English for the search only.
3. ANSWER. A language model on Groq writes the answer using only those sources, with rules:
   cite every fact, copy numbers exactly, otherwise reply "I don't know based on my sources."
4. CHECK (in code, not trusted to the model). Every citation must be one of the given ids, and every
   number in the answer must appear in the sources (or the question). If not, the model gets one
   chance to fix it; if it still fails, the agent answers "I don't know" instead of guessing.
5. LOG. Every question, answer, citation and check result goes to data/logs/agent_log.jsonl.
"""
from __future__ import annotations

import json
import os
import re
import time
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable

import pandas as pd

from smog import config

IDK_EN = "I don't know based on my sources."
IDK_UR = "میرے ذرائع کی بنیاد پر میں یہ نہیں جانتا۔"
TOP_K = 4
UNHEALTHY = 55.5
CITY_NAMES = {"lahore": "Lahore", "islamabad_rawalpindi": "Islamabad/Rawalpindi",
              "peshawar": "Peshawar", "karachi": "Karachi"}
URDU_DIGITS = str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")

SYSTEM_PROMPT = f"""You are the Insight Agent of a next-day smog (PM2.5) forecasting project for Lahore,
Islamabad/Rawalpindi, Peshawar and Karachi in Pakistan. You help environment officers and citizens.

Answer ONLY from the SOURCES in the user message. Rules:
1. End every sentence that states a fact or a number with one or more citations, copied exactly from the
   source ids in square brackets, for example [row:pred|lahore|20261021|20261020T1511] or [doc:who-aqg-2021#1].
   Copy each id character for character (plain ASCII hyphens) and put each id in its own brackets.
2. Copy numbers exactly as written in the SOURCES. Never calculate, average, round differently, convert units
   or invent a number.
3. If the SOURCES do not answer the question, reply with exactly this sentence and nothing else:
   {IDK_EN}
   (for a question in Urdu: {IDK_UR})
   This applies to other cities, to dates other than those in the SOURCES, and to unrelated topics. Do not guess.
4. Answer in the language of the question. For Urdu, write Urdu text but keep numbers in 0-9 digits and keep
   citations unchanged.
5. Style: start with a one-sentence direct answer, then at most 3 short sentences with the key supporting
   numbers. Write in plain words for a district environment officer, no headings or bullet lists. When asked why a
   forecast is high or low, name the main reasons and their effects from the source. Do not give medical advice
   beyond what the SOURCES say."""


# --- Sources ---------------------------------------------------------------------------------------

@dataclass
class Source:
    id: str            # citation id, e.g. "doc:who-aqg-2021#1" or "row:cityday|lahore|20261019"
    text: str
    title: str = ""
    url: str = ""


def _frontmatter(text: str) -> tuple[dict, str]:
    if text.startswith("---"):
        import yaml
        _, meta, body = text.split("---", 2)
        return yaml.safe_load(meta) or {}, body
    return {}, text


def load_documents(root: Path | None = None) -> list[Source]:
    """knowledge/*.md plus the project's model card and dataset declaration, split at '## ' headings."""
    root = root or config.ROOT
    files = sorted((root / "knowledge").glob("*.md"))
    extra = {"reports/MODEL_CARD.md": ("model-card", "Model card (generated by python -m smog train)"),
             "DATASET_DECLARATION.md": ("dataset-declaration", "Dataset declaration")}
    chunks: list[Source] = []
    for path in files + [root / p for p in extra if (root / p).exists()]:
        meta, body = _frontmatter(path.read_text(encoding="utf-8"))
        rel = path.relative_to(root).as_posix()
        doc_id = meta.get("id") or extra.get(rel, (path.stem, ""))[0]
        title = meta.get("title") or extra.get(rel, ("", path.stem))[1]
        url = meta.get("url") or f"https://github.com/lazy-laksh/hackinsight-smog-forecast/blob/main/{rel}"
        parts = [p.strip() for p in re.split(r"\n(?=## )", body) if p.strip()]
        for n, part in enumerate(parts, start=1):
            text = re.sub(r"\s+", " ", part.lstrip("#").strip())
            if len(text) > 40:
                chunks.append(Source(f"doc:{doc_id}#{n}", text[:900], title, url))
    return chunks


class Retriever:
    """TF-IDF keyword search over the document chunks (small corpus: transparent and needs no GPU)."""

    def __init__(self, docs: list[Source]):
        from sklearn.feature_extraction.text import TfidfVectorizer
        self.docs = docs
        self.vectorizer = TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True, stop_words="english")
        self.matrix = self.vectorizer.fit_transform([f"{d.title} {d.text}" for d in docs])

    def search(self, query: str, k: int = TOP_K) -> list[tuple[Source, float]]:
        scores = (self.matrix @ self.vectorizer.transform([query]).T).toarray().ravel()
        order = scores.argsort()[::-1][:k]
        return [(self.docs[i], float(scores[i])) for i in order if scores[i] > 0]


# --- Data facts (built by code from gold rows; the model never computes numbers) --------------------

def data_folder() -> Path:
    """The published files: AGENT_DATA_DIR if set, otherwise the public Hugging Face dataset."""
    if os.getenv("AGENT_DATA_DIR"):
        return Path(os.environ["AGENT_DATA_DIR"])
    os.environ.setdefault("HF_HUB_DISABLE_SYMLINKS_WARNING", "1")      # quiet Windows cache warning
    os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
    from dotenv import load_dotenv
    load_dotenv(config.ROOT / ".env")                                   # HF_TOKEN avoids the rate-limit warning
    from huggingface_hub import snapshot_download
    repo = os.getenv("HF_DATASET_REPO") or (config.load_yaml("agent") or {}).get("data_repo")
    return Path(snapshot_download(repo, repo_type="dataset"))


def _csv(folder: Path, name: str) -> pd.DataFrame:
    try:
        return pd.read_csv(folder / name)
    except Exception:
        return pd.DataFrame()


def _json(folder: Path, name: str) -> dict:
    try:
        return json.loads((folder / name).read_text(encoding="utf-8"))
    except Exception:
        return {}


def _pkt(ts) -> str:
    return pd.Timestamp(ts).tz_convert("Asia/Karachi").strftime("%Y-%m-%d %H:%M PKT")


def build_facts(folder: Path) -> list[Source]:
    facts: list[Source] = []
    pred = _csv(folder, "predictions.csv")
    if len(pred) and "issued_utc" in pred:
        pred["issued"] = pd.to_datetime(pred["issued_utc"], utc=True, format="mixed")
        latest = pred[pred["issued"] == pred["issued"].max()]
        for r in latest.itertuples():
            city = CITY_NAMES.get(r.city_id, r.city_id)
            text = (f"{city} forecast for {r.target_day_pkt} (issued {_pkt(r.issued)}): mean PM2.5 {r.pm25_pred:.1f} "
                    f"µg/m³, 80% range {r.pm25_p10:.1f} to {r.pm25_p90:.1f} µg/m³")
            if pd.notna(getattr(r, "p_unhealthy", None)):
                text += (f", chance of an unhealthy day (mean of {UNHEALTHY} or more) {round(100 * r.p_unhealthy)}%, "
                         f"default advice (R = 3): {'issue a smog advisory' if bool(r.advisory_default) else 'no advisory'}")
            try:
                drivers = json.loads(r.drivers_json)[:3]
                text += ". Main reasons compared with a typical day: " + "; ".join(
                    f"{d['driver']} {d['effect_ugm3']:+.1f} µg/m³" for d in drivers)
            except Exception:
                pass
            text += f". Persistence baseline (today so far): {r.baseline_persistence:.1f} µg/m³."
            facts.append(Source(f"row:{r.row_id}", text, "gold.predictions", ""))
    daily = _csv(folder, "city_daily.csv")
    if len(daily):
        daily["day_pkt"] = pd.to_datetime(daily["day_pkt"])
        recent = daily[daily["day_pkt"] >= daily["day_pkt"].max() - pd.Timedelta(days=6)]
        for r in recent.itertuples():
            done = "complete day" if bool(r.complete) else f"partial day, {getattr(r, 'hours_covered', '?')} hours so far"
            facts.append(Source(f"row:{r.row_id}", f"{CITY_NAMES.get(r.city_id, r.city_id)} measured mean PM2.5 on "
                                f"{r.day_pkt:%Y-%m-%d}: {r.pm25_mean:.1f} µg/m³ ({done}).", "gold.city_daily"))
    for r in _csv(folder, "freshness.csv").itertuples():
        facts.append(Source(f"row:freshness|{re.sub(r'[^A-Za-z0-9_]+', '_', str(r.source)).strip('_')}", f"Data source {r.source}: newest data {_pkt(r.newest_utc)}, "
                            f"{r.age_hours} hours old at publishing time (allowed {r.limit_hours} hours), status {r.status}.",
                            "gold.freshness"))
    status = _json(folder, "pipeline_status.json")
    if status:
        last, ok = status.get("last_run") or {}, (status.get("last_success") or {}).get("finished_utc")
        facts.append(Source("row:pipeline_status", f"Last hourly pipeline run: {last.get('status')} "
                            f"(finished {_pkt(last['finished_utc']) if last.get('finished_utc') else 'unknown'}); "
                            f"last successful run finished {_pkt(ok) if ok else 'never'}.", "pipeline_status.json"))
    m = _json(folder, "reports/model_metrics.json")
    if m.get("test"):
        t = m["test"]
        facts.append(Source("report:model_metrics", (
            f"On the locked test period ({m['test_rows']} city-days, target days {m['test_target_days'][0]} to "
            f"{m['test_target_days'][1]}) the model's mean absolute error was {t['model']['mae']} µg/m³ versus "
            f"{t['baseline_same_info']['mae']} µg/m³ for persistence, {t['improvement_vs_baseline_pct']}% better. "
            f"The 80% range held the real value {round(100 * t['interval_80_coverage'])}% of the time."), "model_metrics.json"))
    for r in _csv(folder, "reports/test_errors_by_city.csv").itertuples():
        facts.append(Source(f"report:test_errors|{r.city}", (
            f"Test period in {CITY_NAMES.get(r.city, r.city)}: model MAE {r.model_mae} µg/m³, persistence MAE "
            f"{r.baseline_mae} µg/m³, improvement {r.improvement_pct}% (negative means worse than persistence), "
            f"bias {r.model_bias} µg/m³."), "test_errors_by_city.csv"))
    return facts


# --- Checking the answer ---------------------------------------------------------------------------

NUMBER = re.compile(r"(?<![\w.])-?\d[\d,]*(?:\.\d+)?")
CITATION = re.compile(r"\[((?:doc|row|report):[^\]]+)\]")


def _numbers(text: str) -> list[float]:
    text = CITATION.sub(" ", text.translate(URDU_DIGITS))
    out = []
    for m in NUMBER.findall(text):
        try:
            out.append(float(m.replace(",", "")))
        except ValueError:
            pass
    return out


DASHES = str.maketrans({c: "-" for c in "\u2010\u2011\u2012\u2013\u2014\u2015\u2212"} |
                       {c: " " for c in "\u00a0\u202f\u2009\u2007"})


BRACKETS = str.maketrans({"【": "[", "】": "]", "［": "[", "］": "]", "〔": "[", "〕": "]", "〖": "[", "〗": "]"})


def normalise(text: str) -> str:
    """Undo common model habits so a correct citation is not rejected on formatting alone:
    non-breaking hyphens/spaces ('pak\u2011neqs'), wide brackets ('【row:...】', the gpt-oss style),
    '†' location suffixes inside a citation, and citations written in round brackets."""
    text = text.translate(DASHES).translate(BRACKETS)
    text = re.sub(r"\[((?:doc|row|report):[^\]†]*)†[^\]]*\]", r"[\1]", text)
    text = re.sub(r"\(((?:doc|row|report):[^)\s]*)\)", r"[\1]", text)
    text = re.sub(r"\[\[([^\]]+)\]\]", r"[\1]", text)
    return text


def bracket_known_ids(answer: str, ids: set[str]) -> str:
    """If the model wrote a real source id without brackets, add them (only for ids that really exist)."""
    for i in sorted(ids, key=len, reverse=True):
        answer = re.sub(r"(?<![\[\w|:#-])" + re.escape(i) + r"(?![\w|#-]*\])(?![\w|#-])", f"[{i}]", answer)
    return answer


def cited_ids(answer: str) -> list[str]:
    """All ids inside [...] citations; several ids may share one bracket, split by ',' ';' or spaces."""
    out = []
    for group in CITATION.findall(normalise(answer)):
        out += [p.strip() for p in re.split(r"[,;]?\s+(?=(?:doc|row|report):)|[,;]\s*(?=(?:doc|row|report):)", group) if p.strip()]
    return out


def is_idk(answer: str) -> bool:
    return answer.strip().strip('"') in (IDK_EN, IDK_UR) or answer.strip().startswith(("I don't know", IDK_UR[:20]))


def check(answer: str, sources: list[Source], question: str = "") -> list[str]:
    """Problems with an answer (empty list = passes). Done in code so the model cannot talk its way past it."""
    if is_idk(answer):
        return []
    problems = []
    ids = {s.id for s in sources}
    answer = bracket_known_ids(normalise(answer), ids)
    cited = cited_ids(answer)
    if not cited:
        problems.append("no citation")
    problems += [f"unknown citation [{c}]" for c in cited if c not in ids]
    allowed = _numbers(" ".join(s.text for s in sources) + " " + question)
    for n in _numbers(answer):
        if not any(abs(abs(n) - abs(a)) <= 0.051 for a in allowed):     # sign ignored: "−3" vs "-3"
            problems.append(f"number {n:g} is not in the sources")
    return problems


# --- The language model ----------------------------------------------------------------------------

# --- Language models: a chain of free, OpenAI-compatible providers ----------------------------------
# Tried in order. A provider whose key is missing is skipped; a model that is rate-limited for longer than
# MAX_WAIT_S is skipped (and remembered as busy) so the user never waits minutes. Every answer, from any
# model, goes through the same citation and number checks. The chain lives in config/agent.yaml.
DEFAULT_PROVIDERS = [
    {"name": "groq", "base_url": "https://api.groq.com/openai/v1", "key_env": "GROQ_API_KEY",
     "models": ["openai/gpt-oss-120b"]},
    {"name": "gemini", "base_url": "https://generativelanguage.googleapis.com/v1beta/openai", "key_env": "GEMINI_API_KEY",
     "models": ["gemini-3.8-flash", "gemini-3.5-flash", "gemini-2.5-flash"]},
    {"name": "groq", "base_url": "https://api.groq.com/openai/v1", "key_env": "GROQ_API_KEY",
     "models": ["openai/gpt-oss-20b"]},
]
NOT_CHAT = ("whisper", "guard", "tts", "orpheus", "playai", "compound", "prompt-guard", "distil", "embedding",
            "image", "veo", "imagen", "audio", "live")
MAX_WAIT_S = 30                         # wait at most this long for a rate limit before moving down the chain
last_model_used: str | None = None      # which model wrote the latest answer (shown in logs and the eval)
_busy_until: dict[str, float] = {}      # "provider:model" -> time when its rate limit should be over
_missing: set[str] = set()              # "provider:model" pairs the provider says do not exist


def providers() -> list[dict]:
    from dotenv import load_dotenv
    load_dotenv(config.ROOT / ".env")
    chain = (config.load_yaml("agent") or {}).get("providers") or DEFAULT_PROVIDERS
    return [p for p in chain if os.getenv(p["key_env"])]


def list_models() -> dict[str, list[str]]:
    """Chat models each configured provider offers to this account (python -m smog agent-models)."""
    import requests
    out = {}
    for p in providers():
        try:
            r = requests.get(p["base_url"].rstrip("/") + "/models",
                             headers={"Authorization": f"Bearer {os.environ[p['key_env']]}"}, timeout=30)
            r.raise_for_status()
            ids = [m["id"].removeprefix("models/") for m in r.json().get("data", [])]
            out[p["name"]] = sorted(i for i in ids if not any(w in i.lower() for w in NOT_CHAT))
        except Exception as error:
            out[p["name"]] = [f"(could not list: {error})"]
    return out


def llm_chat(messages: list[dict], max_tokens: int = 1500) -> str:
    import requests
    global last_model_used
    chain = providers()
    if not chain:
        raise RuntimeError("no language model key found: put GROQ_API_KEY and/or GEMINI_API_KEY in .env")
    problems = []
    for p in chain:
        key = os.environ[p["key_env"]]
        for model in p["models"]:
            tag = f"{p['name']}:{model}"
            if tag in _missing or _busy_until.get(tag, 0) > time.time():
                continue
            for attempt in range(4):
                body = {"model": model, "messages": messages, "temperature": 0, "max_tokens": max_tokens}
                try:
                    r = requests.post(p["base_url"].rstrip("/") + "/chat/completions", timeout=90, json=body,
                                      headers={"Authorization": f"Bearer {key}"})
                except requests.RequestException as error:
                    problems.append(f"{tag}: {error}")
                    break
                if r.status_code == 404:
                    _missing.add(tag)
                    problems.append(f"{tag}: model not available")
                    break
                if r.status_code == 429:
                    wait = float(r.headers.get("retry-after", 2 ** attempt * 5))
                    if wait > MAX_WAIT_S or attempt == 3:
                        _busy_until[tag] = time.time() + wait
                        print(f"(note: {tag} is rate-limited for {wait:.0f}s; trying the next model)")
                        problems.append(f"{tag}: rate-limited")
                        break
                    time.sleep(wait)
                    continue
                if r.status_code in (500, 502, 503) and attempt < 3:
                    time.sleep(2 ** attempt)
                    continue
                if r.status_code >= 400:
                    problems.append(f"{tag}: HTTP {r.status_code} {r.text[:150]}")
                    break
                text = (r.json()["choices"][0]["message"].get("content") or "")
                last_model_used = tag
                return re.sub(r"<think>.*?</think>", "", text, flags=re.S).strip()   # some models show their reasoning
    raise RuntimeError("every language model is busy or unavailable right now (" + "; ".join(problems[-3:]) +
                       "). Try again in a few minutes.")


groq_chat = llm_chat        # old name, kept so earlier scripts keep working


# --- The agent -------------------------------------------------------------------------------------

@dataclass
class Answer:
    question: str
    answer: str
    verified: bool
    citations: list[dict] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)
    retrieved: list[str] = field(default_factory=list)
    language: str = "en"
    attempts: int = 1
    seconds: float = 0.0
    rejected: list[str] = field(default_factory=list)     # model answers that failed the check (for the log)
    model: str = ""                                        # which language model wrote the answer


class InsightAgent:
    def __init__(self, folder: Path | None = None, llm: Callable[[list[dict]], str] | None = None,
                 root: Path | None = None):
        self.llm = llm or llm_chat
        self.docs = load_documents(root)
        self.retriever = Retriever(self.docs)
        self.fixed_folder = folder
        self.facts = build_facts(folder or data_folder())
        self.loaded_at = time.time()

    REFRESH_S = 600

    def refresh(self) -> None:
        """When reading the live dataset, pick up the newest hourly results (at most every 10 minutes)."""
        if self.fixed_folder is None and os.getenv("AGENT_DATA_DIR") is None and time.time() - self.loaded_at > self.REFRESH_S:
            try:
                self.facts = build_facts(data_folder())
            except Exception as error:             # keep answering from the last good copy
                print(f"(note: could not refresh the published data: {error})")
            self.loaded_at = time.time()

    CITY_WORDS = {"lahore": ("lahore", "لاہور"), "karachi": ("karachi", "کراچی"), "peshawar": ("peshawar", "پشاور"),
                  "islamabad_rawalpindi": ("islamabad", "rawalpindi", "pindi", "اسلام آباد", "راولپنڈی")}

    TOPICS = {   # fact groups that are only sent when the question is about them (keeps prompts small)
        "status": ("row:freshness|", "row:pipeline_status",
                   ("fresh", "stale", "data", "update", "run", "pipeline", "latest", "current", "now", "quality", "source")),
        "skill": ("report:",
                  ("accura", "error", "test", "baseline", "persistence", "model", "better", "worse", "reliab", "trust",
                   "mae", "good is", "how good", "perform", "skill", "wrong", "right")),
    }

    def select_facts(self, text: str) -> list[Source]:
        """Tomorrow's forecasts always; measured days only for the cities asked about (all cities, last 3 days,
        if none is named); run status and test results only when the question is about them.
        Smaller prompts mean faster answers, fewer rate limits and a more focused model."""
        low = text.lower()
        named = [c for c, words in self.CITY_WORDS.items() if any(w in low for w in words)]
        wanted = {name for name, (*_, words) in self.TOPICS.items() if any(w in low for w in words)}
        out = []
        for f in self.facts:
            topic = next((name for name, (*prefixes, _) in self.TOPICS.items()
                          if any(f.id.startswith(p) for p in prefixes)), None)
            if topic and topic not in wanted:
                continue
            if f.id.startswith("row:cityday|"):
                parts = f.id.split("|") + ["", ""]
                city, day = parts[1], parts[2]
                if named and city not in named:
                    continue
                if not named and day < self._recent_cutoff:
                    continue
            out.append(f)
        return out

    @property
    def _recent_cutoff(self) -> str:
        days = sorted({(f.id.split("|") + ["", ""])[2] for f in self.facts if f.id.startswith("row:cityday|")})
        return days[-3] if len(days) >= 3 else ""

    @staticmethod
    def is_urdu(text: str) -> bool:
        return bool(re.search(r"[؀-ۿ]", text))

    def ask(self, question: str, log: bool = True) -> Answer:
        self.refresh()
        start = time.time()
        urdu = self.is_urdu(question)
        idk = IDK_UR if urdu else IDK_EN
        query = question
        if urdu:          # search the English documents with an English version of the question
            query = self.llm([{"role": "system", "content": "Translate the user's text to English. Output only the translation."},
                              {"role": "user", "content": question}])
        hits = self.retriever.search(query)
        sources = self.select_facts(question + " " + query) + [d for d, _ in hits]
        block = "\n".join(f"[{s.id}] {s.text}" for s in sources)
        messages = [{"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": f"SOURCES:\n{block}\n\nQUESTION: {question}"}]
        answer, rejected, attempts = self.llm(messages), [], 1
        problems = check(answer, sources, question)
        if problems:      # one chance to fix it, with the exact problems listed
            attempts = 2
            rejected.append(answer)
            messages += [{"role": "assistant", "content": answer},
                         {"role": "user", "content": "Your answer broke the rules: " + "; ".join(problems) +
                          f". Rewrite it using only the SOURCES, or reply exactly: {idk}"}]
            answer = self.llm(messages)
            problems = check(answer, sources, question)
        verified = not problems
        if not verified:  # never show an unchecked answer
            rejected.append(answer)
            answer = idk
        by_id = {s.id: s for s in sources}
        answer = bracket_known_ids(normalise(answer), set(by_id))
        cited = sorted(set(cited_ids(answer)))
        result = Answer(question, answer, verified, [
            {"id": c, "title": by_id[c].title, "url": by_id[c].url, "text": by_id[c].text} for c in cited if c in by_id],
            problems, [d.id for d, _ in hits], "ur" if urdu else "en", attempts, round(time.time() - start, 1), rejected,
            last_model_used or "")
        if log:
            path = config.ROOT / "data/logs/agent_log.jsonl"
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("a", encoding="utf-8") as f:
                f.write(json.dumps({"asked_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                                    **asdict(result)}, ensure_ascii=False) + "\n")
        return result


def format_answer(a: Answer) -> str:
    lines = [a.answer, ""]
    for n, c in enumerate(a.citations, 1):
        where = c["url"] or c["title"]
        lines.append(f"  [{n}] {c['id']}  {c['title']}  {where}".rstrip())
    status = "yes" if a.verified else "NO, so the answer was replaced by I don't know: " + "; ".join(a.problems)
    lines.append(f"  (checked: {status}; model: {a.model or '-'}; {a.seconds}s)")
    return "\n".join(lines)


# --- Golden evaluation set -------------------------------------------------------------------------

def evaluate(agent: InsightAgent, path: Path | None = None) -> pd.DataFrame:
    """Run the questions in config/agent_golden.yaml and score each answer automatically."""
    golden = config.load_yaml("agent_golden")["questions"]
    rows = []
    for q in golden:
        a = agent.ask(q["question"])
        cited = [c["id"] for c in a.citations]
        checks = {"verified": a.verified}
        if q["expect"] == "idk":
            checks["said I don't know"] = is_idk(a.answer)
        else:
            checks["answered"] = not is_idk(a.answer)
            for prefix in q.get("cite", []):
                checks[f"cites {prefix}"] = any(c.startswith(prefix) for c in cited)
            for text in q.get("must_include", []):
                checks[f"says {text}"] = text in a.answer
        if q.get("lang") == "ur":
            checks["answered in Urdu"] = InsightAgent.is_urdu(a.answer)
        rows.append({"id": q["id"], "question": q["question"], "expect": q["expect"],
                     "passed": all(checks.values()), "failed_checks": "; ".join(k for k, v in checks.items() if not v),
                     "problems": "; ".join(a.problems), "rejected_answers": " || ".join(a.rejected), "answer": a.answer, "citations": " ".join(cited),
                     "model": a.model, "seconds": a.seconds})
        time.sleep(1)     # stay well inside the free API rate limit
    df = pd.DataFrame(rows)
    out = path or config.ROOT / "reports/agent_eval.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out, index=False)
    return df
